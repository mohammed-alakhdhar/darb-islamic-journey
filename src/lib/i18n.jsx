const LANG_KEY = 'darb_lang_v1';
const DEFAULT_LANG = 'ar';

function readLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored && LANGUAGES.some((l) => l.code === stored)) return stored;
  } catch { /* ignore */ }
  return DEFAULT_LANG;
}

